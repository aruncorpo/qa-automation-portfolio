import sqlite3
from pathlib import Path
connect = sqlite3.connect(Path(__file__).resolve().parent.parent / "database" / "qa_practice.db")
cur = connect.cursor()

cur.execute("DELETE FROM orders where order_id = 105")
cur.execute("SELECT * FROM orders where order_id = 105")
data = cur.fetchall()
print(data)
cur.execute("ROLLBACK")
cur.execute("SELECT * FROM orders where order_id = 105")
data = cur.fetchall()
print(data)

connect.commit()
connect.close()

